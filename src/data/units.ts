export interface UnitTypeDef {
  id: UnitTypeId;
  name: string;
  speciesId: 'brutes' | 'nobles' | 'weirdos';
  maxHp: number;
  dmg: number;
  range: number;
  speed: number;
  radius: number;
  vision: number;
  attackCooldownMs: number;
  canGather: boolean;
  carryCapacity: number;
  costGold: number;
  costCrystals: number;
  trainMs: number;
  /** Structure bonus damage multiplier (siege). */
  structureMult?: number;
  /** Participates in FORMATIONS when Nobles. */
  usesFormation?: boolean;
  /** Participates in MUTATION when Weirdos. */
  canMutate?: boolean;
  /** Participates in RAGE when Brutes. */
  canRage?: boolean;
  isHero?: boolean;
  /** Shape hint for presentation placeholders. */
  shape?: 'circle' | 'square' | 'diamond' | 'triangle' | 'hex' | 'star';
}

